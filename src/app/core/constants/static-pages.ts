/**
 * The seven pages, in the bundle (FR-CMS-01).
 *
 * In `core/` rather than beside the feature that renders them because the mock
 * interceptor answers `/content/pages/:slug` from the same documents, and
 * `core/` may not import from `features/`. One copy either way: the mock
 * re-exports this, so both modes serve the same text and neither can drift.
 *
 * These are the documents themselves — "من نحن", the FAQ, the terms, the
 * privacy and refund policies, the contact page — as reviewed in the design
 * export. They are not fixtures and they are not placeholders.
 *
 * They ship here because the CMS module does not exist yet: every
 * `/content/pages/:slug` answers 404, and four of these are links in the header
 * and the footer of every screen. A visitor's second click was landing on an
 * error, and "we could not load the terms" is not something to show somebody
 * who came to read the terms.
 *
 * **This is not a decision to keep content in code.** `ContentService` asks the
 * server first and only falls back to these; the day the CMS ships, an
 * administrator's published version wins with no change here. Then these become
 * what they should be — the copy of last resort when the CMS is unreachable,
 * which for a legal document is worth having anyway.
 *
 * So when you edit one of these: it is the launch text, and it stops being
 * authoritative the moment the backend serves the same slug.
 */

